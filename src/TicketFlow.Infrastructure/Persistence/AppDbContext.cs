using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;
using TicketFlow.Application.Abstractions;
using TicketFlow.Domain.Common;
using TicketFlow.Domain.Events;
using TicketFlow.Domain.Orders;
using TicketFlow.Domain.Tickets;
using TicketFlow.Domain.Users;

namespace TicketFlow.Infrastructure.Persistence;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options), IAppDbContext
{
    /// <summary>Shadow property used as optimistic-concurrency token on every aggregate root.</summary>
    public const string VersionProperty = "Version";

    public DbSet<User> Users => Set<User>();
    public DbSet<RefreshToken> RefreshTokens => Set<RefreshToken>();
    public DbSet<Event> Events => Set<Event>();
    public DbSet<TicketTier> TicketTiers => Set<TicketTier>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<Ticket> Tickets => Set<Ticket>();

    public override Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        // Every write to an aggregate gets a fresh version. EF adds "WHERE Version = @original" to the
        // UPDATE, so a concurrent writer that read the old version fails with DbUpdateConcurrencyException.
        foreach (var entry in ChangeTracker.Entries<AggregateRoot>())
        {
            if (entry.State is EntityState.Added or EntityState.Modified)
            {
                entry.Property<Guid>(VersionProperty).CurrentValue = Guid.NewGuid();
            }
        }

        return base.SaveChangesAsync(cancellationToken);
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(AppDbContext).Assembly);

        foreach (var entityType in modelBuilder.Model.GetEntityTypes()
                     .Where(t => typeof(Entity).IsAssignableFrom(t.ClrType)))
        {
            var entity = modelBuilder.Entity(entityType.ClrType);

            // Ids are generated by the domain (UUIDv7). Telling EF they are never store-generated makes it
            // INSERT new children discovered through navigations (e.g. tickets issued by Order.MarkPaid)
            // instead of assuming "key is set => existing row" and issuing an UPDATE.
            entity.Property(nameof(Entity.Id)).ValueGeneratedNever();

            if (typeof(AggregateRoot).IsAssignableFrom(entityType.ClrType))
            {
                entity.Property<Guid>(VersionProperty).IsConcurrencyToken();
            }
        }
    }

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        // SQLite (local dev & tests) has no native decimal or DateTimeOffset type and cannot ORDER BY / compare
        // them. These converters (recommended by the EF Core docs) keep queries translatable there.
        // PostgreSQL uses native numeric / timestamptz columns and is unaffected.
        if (Database.ProviderName == "Microsoft.EntityFrameworkCore.Sqlite")
        {
            configurationBuilder.Properties<decimal>().HaveConversion<double>();
            configurationBuilder.Properties<DateTimeOffset>().HaveConversion<DateTimeOffsetToBinaryConverter>();
        }
    }
}
